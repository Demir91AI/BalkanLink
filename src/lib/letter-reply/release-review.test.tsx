import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';
import { afterEach, expect, it, vi } from 'vitest';
import { createInstance } from 'i18next';
import { I18nextProvider } from 'react-i18next';
import LetterReplyTask from '@/components/letter-reply/LetterReplyTask';
import de from '@/i18n/locales/de/reply.json';

afterEach(() => { cleanup(); vi.unstubAllEnvs(); });
it('production wizard requires both reviews and discards the draft on close', async () => {
  vi.stubEnv('DEV', false);
  const i18n = createInstance();
  await i18n.init({ lng: 'de', resources: { de: { reply: de } }, interpolation: { escapeValue: false } });
  render(<I18nextProvider i18n={i18n}><MemoryRouter><LetterReplyTask canAccess /></MemoryRouter></I18nextProvider>);
  fireEvent.click(screen.getByRole('button', { name: new RegExp(de.title) }));
  fireEvent.click(screen.getByRole('button', { name: de.purposes.documents }));
  fireEvent.click(screen.getByRole('button', { name: de.next }));
  fireEvent.change(screen.getByLabelText(de.fields.date), { target: { value: '2026-10-27' } });
  fireEvent.change(screen.getByLabelText(de.fields.sender), { target: { value: 'Maja Čičak' } });
  fireEvent.change(screen.getByLabelText(de.fields.attachments), { target: { value: 'Geburtsurkunde' } });
  fireEvent.click(screen.getByRole('button', { name: de.next }));
  expect(screen.getByRole('button', { name: de.generate })).toBeDisabled();
  fireEvent.click(screen.getByRole('checkbox', { name: de.reviewConfirm }));
  fireEvent.click(screen.getByRole('button', { name: de.generate }));
  expect(screen.getByLabelText(de.documentTitle)).toHaveValue(expect.stringContaining('Maja Čičak'));
  expect(screen.getByRole('button', { name: de.pdf })).toBeDisabled();
  expect(screen.getByRole('button', { name: de.copy })).toBeDisabled();
  fireEvent.click(screen.getByRole('checkbox', { name: de.editConfirm }));
  expect(screen.getByRole('button', { name: de.pdf })).toBeEnabled();
  fireEvent.change(screen.getByLabelText(de.documentTitle), { target: { value: 'Geänderter Text' } });
  expect(screen.getByRole('button', { name: de.pdf })).toBeDisabled();
  fireEvent.click(screen.getByRole('button', { name: de.close }));
  fireEvent.click(screen.getByRole('button', { name: new RegExp(de.title) }));
  fireEvent.click(screen.getByRole('button', { name: de.purposes.documents }));
  fireEvent.click(screen.getByRole('button', { name: de.next }));
  expect(screen.getByLabelText(de.fields.sender)).toHaveValue('');
});