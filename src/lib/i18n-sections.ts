/** Get a section translation. Falls back: language → bs → key */
export function getSectionT(lang: Lang, key: string): string {
  const all = { ...docCheckTranslations[lang], ...vizaTranslations[lang], ...ntTranslations[lang] };
  if (all[key]) return all[key];
  // fallback to bs
  const bsAll = { ...docCheckTranslations.bs, ...vizaTranslations.bs, ...ntTranslations.bs };
  return bsAll[key] ?? key;
}
