/// <reference types="npm:@types/react@18.3.1" />
import * as React from 'npm:react@18.3.1'
import {
  Body, Container, Head, Heading, Html, Preview, Section, Text, Hr,
} from 'npm:@react-email/components@0.0.22'
import type { TemplateEntry } from './registry.ts'

interface MismatchRow {
  email?: string
  status?: string
  issue?: string | null
  db_expires_at?: string | null
  stripe_period_end?: string | null
  diff_days?: number | null
}

interface Props {
  outcome?: 'mismatch' | 'success' | 'failure'
  headline?: string
  message?: string
  checkedAt?: string
  stripeActive?: number
  mismatches?: number
  fixed?: number
  rows?: MismatchRow[]
}

const colorFor = (outcome?: string) =>
  outcome === 'failure' ? '#dc2626' : outcome === 'mismatch' ? '#d97706' : '#16a34a'

const AdminStripeSyncEmail = ({
  outcome = 'mismatch',
  headline = 'Stripe sync izvještaj',
  message = '',
  checkedAt,
  stripeActive,
  mismatches,
  fixed,
  rows = [],
}: Props) => (
  <Html lang="bs" dir="ltr">
    <Head />
    <Preview>{headline}</Preview>
    <Body style={main}>
      <Container style={container}>
        <Heading style={{ ...h1, color: colorFor(outcome) }}>📋 {headline}</Heading>
        {message ? <Text style={text}>{message}</Text> : null}

        <Section style={card}>
          <Text style={row}><strong>Vrijeme provjere:</strong> {checkedAt ?? '—'}</Text>
          <Text style={row}><strong>Aktivnih Stripe pretplata:</strong> {stripeActive ?? '—'}</Text>
          <Text style={row}><strong>Neslaganja (mismatch):</strong> {mismatches ?? 0}</Text>
          <Text style={row}><strong>Automatski ispravljeno:</strong> {fixed ?? 0}</Text>
        </Section>

        {rows.length > 0 ? (
          <>
            <Text style={text}><strong>Detalji neslaganja</strong></Text>
            {rows.map((r, i) => (
              <Section key={i} style={card}>
                <Text style={row}><strong>Korisnik:</strong> {r.email ?? '—'}</Text>
                <Text style={row}><strong>Status:</strong> {r.status ?? '—'}</Text>
                <Text style={row}><strong>Problem:</strong> {r.issue ?? '—'}</Text>
                <Text style={row}>
                  <strong>Baza:</strong> {r.db_expires_at ?? '—'} · <strong>Stripe:</strong> {r.stripe_period_end ?? '—'}
                  {typeof r.diff_days === 'number' ? ` (${r.diff_days > 0 ? '+' : ''}${r.diff_days} dana)` : ''}
                </Text>
              </Section>
            ))}
          </>
        ) : null}

        <Hr style={hr} />
        <Text style={footer}>Auto-generated by stripe-sync-audit · BalkanLink</Text>
      </Container>
    </Body>
  </Html>
)

export const template = {
  component: AdminStripeSyncEmail,
  subject: (d: Record<string, any>) => {
    const o = d?.outcome
    if (o === 'failure') return '[BalkanLink] Stripe sync NEUSPJEŠAN'
    if (o === 'success') return '[BalkanLink] Stripe sync uspješan'
    return `[BalkanLink] Stripe mismatch — ${d?.mismatches ?? 0} neslaganja`
  },
  displayName: 'Admin – Stripe sync',
  to: 'kontakt@balkanlink.de',
  previewData: {
    outcome: 'mismatch',
    headline: 'Otkriveno neslaganje Stripe ↔ baza',
    message: 'Pronađena su 2 neslaganja između Stripe pretplata i baze.',
    checkedAt: new Date().toISOString(),
    stripeActive: 2,
    mismatches: 2,
    fixed: 0,
    rows: [
      {
        email: 'korisnik@example.com',
        status: 'date_mismatch',
        issue: 'Razlika u datumu isteka: +31 dana',
        db_expires_at: '2026-07-01T00:00:00.000Z',
        stripe_period_end: '2026-08-01T00:00:00.000Z',
        diff_days: 31,
      },
    ],
  },
} satisfies TemplateEntry

const main = { backgroundColor: '#ffffff', fontFamily: 'Arial, sans-serif' }
const container = { padding: '24px', maxWidth: '600px', margin: '0 auto' }
const h1 = { fontSize: '22px', fontWeight: 'bold' as const, margin: '0 0 16px' }
const text = { fontSize: '14px', color: '#334155', lineHeight: '1.5', margin: '0 0 16px' }
const card = { background: '#f8fafc', border: '1px solid #e2e8f0', borderRadius: '8px', padding: '16px', margin: '12px 0' }
const row = { fontSize: '13px', color: '#0f172a', margin: '4px 0' }
const hr = { borderColor: '#e2e8f0', margin: '24px 0' }
const footer = { fontSize: '12px', color: '#94a3b8', margin: '0' }
