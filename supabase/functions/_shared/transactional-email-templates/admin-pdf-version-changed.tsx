/// <reference types="npm:@types/react@18.3.1" />
import * as React from 'npm:react@18.3.1'
import {
  Body, Container, Head, Heading, Html, Preview, Section, Text, Hr, Link,
} from 'npm:@react-email/components@0.0.22'
import type { TemplateEntry } from './registry.ts'

interface Change {
  form_key: string
  source_url: string
  old?: { etag?: string | null; last_modified?: string | null; content_length?: number | null }
  new?: { etag?: string | null; last_modified?: string | null; content_length?: number | null }
}

interface Props {
  changes?: Change[]
}

const AdminPdfVersionChangedEmail = ({ changes = [] }: Props) => (
  <Html lang="bs" dir="ltr">
    <Head />
    <Preview>ZBFS PDF promijenjen — provjeri lokalne template</Preview>
    <Body style={main}>
      <Container style={container}>
        <Heading style={h1}>📋 ZBFS PDF version change</Heading>
        <Text style={text}>
          Sljedeći eksterni PDF formulari su se promijenili. Provjeri da li treba ažurirati lokalni template i field mapping u projektu.
        </Text>

        {changes.map((c, i) => (
          <Section key={i} style={card}>
            <Text style={row}><strong>Form:</strong> {c.form_key}</Text>
            <Text style={row}>
              <strong>URL:</strong>{' '}
              <Link href={c.source_url} style={{ color: '#2563eb' }}>{c.source_url}</Link>
            </Text>
            <Text style={row}><strong>ETag:</strong> {c.old?.etag ?? '—'} → {c.new?.etag ?? '—'}</Text>
            <Text style={row}><strong>Last-Modified:</strong> {c.old?.last_modified ?? '—'} → {c.new?.last_modified ?? '—'}</Text>
            <Text style={row}><strong>Content-Length:</strong> {c.old?.content_length ?? '—'} → {c.new?.content_length ?? '—'}</Text>
          </Section>
        ))}

        <Hr style={hr} />
        <Text style={footer}>Auto-generated by check-pdf-versions cron · BalkanLink</Text>
      </Container>
    </Body>
  </Html>
)

export const template = {
  component: AdminPdfVersionChangedEmail,
  subject: (d: Record<string, any>) =>
    `[BalkanLink] ZBFS PDF promijenjen — ${(d?.changes?.length ?? 0)} formular(a)`,
  displayName: 'Admin – ZBFS PDF promjena',
  to: 'kontakt@balkanlink.de',
  previewData: {
    changes: [{
      form_key: 'elterngeld-bayern',
      source_url: 'https://www.zbfs.bayern.de/imperia/md/content/zbfs/erziehungsgeld/antraege/antrag_elterngeld_05_2025.pdf',
      old: { etag: '"abc123"', last_modified: 'Mon, 05 May 2025 10:00:00 GMT', content_length: 234567 },
      new: { etag: '"xyz789"', last_modified: 'Tue, 11 Nov 2025 09:00:00 GMT', content_length: 245678 },
    }],
  },
} satisfies TemplateEntry

const main = { backgroundColor: '#ffffff', fontFamily: 'Arial, sans-serif' }
const container = { padding: '24px', maxWidth: '600px', margin: '0 auto' }
const h1 = { fontSize: '22px', fontWeight: 'bold' as const, color: '#0f172a', margin: '0 0 16px' }
const text = { fontSize: '14px', color: '#334155', lineHeight: '1.5', margin: '0 0 16px' }
const card = { background: '#f8fafc', border: '1px solid #e2e8f0', borderRadius: '8px', padding: '16px', margin: '12px 0' }
const row = { fontSize: '13px', color: '#0f172a', margin: '4px 0' }
const hr = { borderColor: '#e2e8f0', margin: '24px 0' }
const footer = { fontSize: '12px', color: '#94a3b8', margin: '0' }
