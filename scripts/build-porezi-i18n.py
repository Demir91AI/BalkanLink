def merge_into(lang_code):
    path = LOCALES / lang_code / "porezi.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    # add shared checklist namespace
    data["checklist"] = CHECKLIST[lang_code]
    for module_id, content_by_lang, sources_by_lang, short_names in MODULES:
        block = dict(content_by_lang[lang_code])  # copy
        common = common_block(
            lang_code,
            short_names[lang_code],
            "/porezi/" + module_id,  # placeholder, only used for gate.title cosmetic
            {k: sources_by_lang[k] for k in ("bs","hr","sr","de")},
        )
        block.update(common)
        data[module_id] = block
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"✓ {lang_code}: wrote {len(MODULES)} modules + checklist namespace")


